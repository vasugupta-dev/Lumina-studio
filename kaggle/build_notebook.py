     "            ids = tok(r['text'], return_tensors='pt', truncation=True, max_length=seqlen)['input_ids'].to(dev)\n"
     "            if ids.shape[1] < 3: continue\n"
     "            ctx, tgt = ids[:, :-1], int(ids[0, -1])\n"
     "            pred = int(model(ctx).logits[0, -1].argmax())\n"
     "            hit += int(pred == tgt); tot += 1\n"
