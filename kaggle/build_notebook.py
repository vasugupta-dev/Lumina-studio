     "    ds = load_dataset('EleutherAI/lambada_openai', split='test')\n"
     "    model.eval(); hit, tot = 0, 0\n"
     "    dev = _dev(model)\n"
     "    with torch.no_grad():\n"
     "        for r in ds:\n"
     "            if tot >= n: break\n"
