_SLUG = re.compile(r"^[a-z0-9][a-z0-9_\-]{0,40}$")


def _load_index() -> list[dict]:
    try:
        with open(INDEX) as f:
            d = json.load(f)
        return d if isinstance(d, list) else []
    except Exception:
        return []


def _save_index(defs: list[dict]) -> None:
    os.makedirs(DIR, exist_ok=True)
    tmp = INDEX + ".tmp"
    with open(tmp, "w") as f:
        json.dump(defs, f, indent=1)
    os.replace(tmp, INDEX)


def server_path(server_id: str) -> str:
    return os.path.join(DIR, server_id.replace("/", "_") + ".py")


def validate(body: dict) -> tuple[dict | None, str]:
    sid = str(body.get("id", "")).strip().lower()
    if not _SLUG.match(sid):
        return None, "id must be a slug: lowercase letters/digits/_/- (<=41 chars)"
    tools = body.get("tools")
    if not isinstance(tools, list) or not (1 <= len(tools) <= 16):
        return None, "tools must be a list of 1..16 tool definitions"
    seen = set()
    clean_tools = []
    for t in tools:
        if not isinstance(t, dict):
            return None, "each tool must be an object"
        tn = str(t.get("name", "")).strip().lower()
        if not _SLUG.match(tn):
            return None, "tool name must be a slug: " + str(t.get("name"))[:40]
        if tn in seen:
            return None, "duplicate tool name: " + tn
        seen.add(tn)
        h = t.get("handler") or {}
        kind = str(h.get("kind", "echo"))
        if kind not in KINDS:
            return None, "handler kind must be one of: " + ", ".join(KINDS)
        for req in _REQUIRED[kind]:
            if not str(h.get(req, "")).strip():
                return None, "handler %s requires field '%s'" % (kind, req)
        clean_tools.append({
            "name": tn,
            "description": str(t.get("description", ""))[:300] or ("tool " + tn),
            "input_schema": t.get("input_schema") or {"type": "object"},
            "handler": {k: v for k, v in h.items() if k != "kind"} | {"kind": kind},
        })
    return {"id": sid,
            "name": str(body.get("name", sid))[:80],
            "desc": str(body.get("desc", ""))[:300],
            "tools": clean_tools,
            "created": time.time()}, ""


def save_custom(body: dict) -> dict:
    d, err = validate(body)
    if d is None:
        return {"error": err}
    defs = [x for x in _load_index() if x.get("id") != d["id"]]
    defs.append(d)
    _save_index(defs)
    os.makedirs(DIR, exist_ok=True)
    src = HEADER + "DEF = " + json.dumps(d, indent=1) + "\n" + RUNTIME
    path = server_path(d["id"])
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(src)
    os.replace(tmp, path)
    # self-check: the generated file must at least be valid Python
    import ast as _ast
    try:
        _ast.parse(src)
    except SyntaxError as e:
        return {"error": "generated file failed to parse: " + str(e)[:150]}
    return {"saved": d["id"], "file": path, "bytes": len(src),
            "tools": [t["name"] for t in d["tools"]],
            "kind_counts": {k: sum(1 for t in d["tools"]
                                   if t["handler"]["kind"] == k)
                            for k in KINDS
                            if any(t["handler"]["kind"] == k for t in d["tools"])}}


def list_custom() -> dict:
    defs = _load_index()
    return {"server_dir": DIR, "count": len(defs), "servers": defs,
            "kinds": list(KINDS),
            "handler_docs": {
                "echo": "returns call args as JSON (wiring test)",
                "command": "{cmd} shell template, {cwd} optional, {timeout} seconds",
                "fetch_url": "{url} template; {strip_html} true by default",
                "read_file": "{path} template, {max_bytes} cap",
                "write_file": "{path} and {text} templates",
                "http_json": "POST {url} with args as JSON body",
                "datetime": "current date/time",
            }}


def delete_custom(server_id: str) -> dict:
    sid = str(server_id).strip().lower()
    defs = _load_index()
    keep = [x for x in defs if x.get("id") != sid]
    if len(keep) == len(defs):
        return {"error": "no such custom server: " + sid}
    _save_index(keep)
    path = server_path(sid)
    try:
        if os.path.exists(path):
            os.remove(path)
    except Exception as e:
        return {"error": "index removed but file not: " + str(e)[:120]}
    return {"deleted": sid, "remaining": len(keep)}


def entries() -> list[dict]:
    """Registry entries for the MCP manager (same shape as curated ones)."""
    out = []
    for d in _load_index():
        path = server_path(d["id"])
        if not os.path.exists(path):
            continue
        out.append({
            "id": "custom/" + d["id"],
            "name": d.get("name") or d["id"],
            "category": "custom",
            "desc": (d.get("desc") or "user-authored MCP server") + " · "
                    + ", ".join(t["name"] for t in d.get("tools", []))[:120],
            "transport": "stdio",
            "command": sys.executable,
            "args": [path],
            "env": [],
            "variant": None,
            "install": "generated by Lumina — no install needed",
            "source": "custom",
        })
    return out


