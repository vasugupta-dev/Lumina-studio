RUNTIME = '''

# ---------------------------------------------------------------------------
# Lumina custom-MCP runtime (generated; stdlib only; plain readable source)
# ---------------------------------------------------------------------------
import json as _json, sys as _sys, os as _os, time as _time
import subprocess as _sp, urllib.request as _ur, urllib.error as _ue

MAX_OUT = 8000


def _subst(tpl, args):
    def rep(m):
        return str(args.get(m.group(1), ""))[:4000]
    return _re.sub(r"\\{([A-Za-z_][A-Za-z0-9_]*)\\}", rep, str(tpl))


def _call(name, args):
    tool = next((t for t in DEF["tools"] if t["name"] == name), None)
    if tool is None:
        return {"content": [{"type": "text", "text": "unknown tool: " + name}],
                "isError": True}
    h = tool.get("handler") or {}
    kind = h.get("kind", "echo")
    try:
        if kind == "echo":
            out = _json.dumps({"tool": name, "args": args, "at": _time.time()})
        elif kind == "command":
            p = _sp.run(["/bin/sh", "-c", _subst(h.get("cmd", "echo"), args)],
                        capture_output=True, text=True, errors="replace",
                        timeout=int(h.get("timeout", 30)),
                        cwd=_os.path.expanduser(h["cwd"]) if h.get("cwd") else None)
            out = (p.stdout + p.stderr)[:MAX_OUT] + ("\\n[exit %d]" % p.returncode
                                                    if p.returncode else "")
        elif kind == "fetch_url":
            req = _ur.Request(_subst(h.get("url", ""), args),
                              headers={"User-Agent": "Lumina-custom-mcp/0.1"})
            raw = _ur.urlopen(req, timeout=int(h.get("timeout", 20))).read(120000)
            text = raw.decode("utf-8", "ignore")
            if h.get("strip_html", True):
                import re as _re2
                text = _re2.sub(r"<script.*?</script>|<style.*?</style>", " ", text,
                                flags=_re2.S | _re2.I)
                text = _re2.sub(r"<[^>]+>", " ", text)
                text = _re2.sub(r"\\s+", " ", text).strip()
            out = text[:MAX_OUT]
        elif kind == "read_file":
            path = _os.path.expanduser(_subst(h.get("path", ""), args))
            with open(path, "rb") as f:
                out = f.read(int(h.get("max_bytes", 262144))).decode("utf-8", "replace")
        elif kind == "write_file":
            path = _os.path.expanduser(_subst(h.get("path", ""), args))
            data = _subst(h.get("text", ""), args).encode()[:262144]
            parent = _os.path.dirname(path)
            if parent and not _os.path.isdir(parent):
                _os.makedirs(parent, exist_ok=True)
            with open(path, "wb") as f:
                f.write(data)
            out = "wrote %d bytes to %s" % (len(data), path)
        elif kind == "http_json":
            body = _json.dumps({"args": args}).encode()
            req = _ur.Request(_subst(h.get("url", ""), args), data=body,
                              headers={"Content-Type": "application/json"})
            try:
                resp = _ur.urlopen(req, timeout=int(h.get("timeout", 20)))
                out = "HTTP %d\\n%s" % (resp.status,
                                       resp.read(120000).decode("utf-8", "replace")[:MAX_OUT])
            except _ue.HTTPError as e:
                out = "HTTP %d\\n%s" % (e.code,
                                       e.read(120000).decode("utf-8", "replace")[:MAX_OUT])
        elif kind == "datetime":
            out = _time.strftime("%Y-%m-%d %H:%M:%S %Z")
        else:
            return {"content": [{"type": "text", "text": "unknown handler kind: " + kind}],
                    "isError": True}
        return {"content": [{"type": "text", "text": str(out)[:MAX_OUT]}]}
    except Exception as e:
        return {"content": [{"type": "text", "text": "handler error: " + str(e)[:400]}],
                "isError": True}


def main():
    for line in _sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            req = _json.loads(line)
        except Exception:
            continue
        rid = req.get("id")
        method = req.get("method", "")
        params = req.get("params") or {}
        if method == "initialize":
            res = {"protocolVersion": params.get("protocolVersion", "2024-11-05"),
                   "capabilities": {"tools": {"listChanged": False}},
                   "serverInfo": {"name": DEF["id"], "version": "0.1.0"}}
        elif method == "tools/list":
            res = {"tools": [{"name": t["name"],
                              "description": t.get("description", ""),
                              "inputSchema": t.get("input_schema",
                                                   {"type": "object"})}
                             for t in DEF["tools"]]}
        elif method == "tools/call":
            res = _call(str(params.get("name", "")), params.get("arguments") or {})
        elif method in ("notifications/initialized", "notifications/cancelled"):
            continue
        else:
            if rid is None:
                continue
            _sys.stdout.write(_json.dumps({"jsonrpc": "2.0", "id": rid,
                                           "error": {"code": -32601,
                                                     "message": "method not found: " + method}}) + "\\n")
            _sys.stdout.flush()
            continue
        if rid is None:
            continue
        _sys.stdout.write(_json.dumps({"jsonrpc": "2.0", "id": rid, "result": res}) + "\\n")
        _sys.stdout.flush()


if __name__ == "__main__":
    main()
'''

