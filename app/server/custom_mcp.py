"""Custom MCP builder: author your own MCP servers from the app.

A "custom MCP" is a REAL Model Context Protocol server, generated by Lumina
as a single stdlib-only Python file that speaks JSON-RPC 2.0 over stdio
(initialize / tools/list / tools/call — the same wire protocol as every
server in mcp_registry.py). You define tools in the UI; each tool's handler
is one of the audited primitives below. The generated file is plain,
readable source you can edit by hand — it is your server, not a black box.

Handler kinds (audited primitives):
  echo        return the call arguments as JSON (smoke-test tool)
  command     run a shell command template, bounded time, capture output
  fetch_url   HTTP GET a URL template, return readable text
  read_file   read a file path template (bounded bytes)
  write_file  write text to a path template (bounded bytes)
  http_json   POST JSON to a URL template, return status + body excerpt
  datetime    return the current date/time (proves round-trips)

Templates use {placeholder} substitution from the tool-call arguments.
Everything is stored under app/server/custom_mcps/ (index.json + one .py
per server); nothing runs until /api/mcp/start or a call — same lazy rules
as the built-in registry.
"""
from __future__ import annotations

import json
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
DIR = os.path.join(HERE, "custom_mcps")
INDEX = os.path.join(DIR, "index.json")

KINDS = ("echo", "command", "fetch_url", "read_file", "write_file",
         "http_json", "datetime")

_REQUIRED = {
    "echo": [],
    "command": ["cmd"],
    "fetch_url": ["url"],
    "read_file": ["path"],
    "write_file": ["path", "text"],
    "http_json": ["url"],
    "datetime": [],
}

